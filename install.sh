#!/usr/bin/env bash
# RestoreProof installer (single host, Docker Compose).
#
#   ./install.sh                                   # install with defaults
#   ./install.sh --repo /mnt/backups/restic        # also mount a local restic repository (read-only)
#   ./install.sh --data /srv/restoreproof --port 8080
#
# Safe to re-run: existing .env, keys and data are never overwritten.
set -euo pipefail

DATA="/var/lib/restoreproof"
PORT="8080"
REPOS=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --data) DATA="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --repo) REPOS+=("$2"); shift 2 ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

cd "$(dirname "$0")"
say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
die() { printf '\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }
SUDO=""; [[ $EUID -ne 0 ]] && command -v sudo >/dev/null && SUDO="sudo"

command -v docker >/dev/null || die "Docker is required: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "the Docker Compose plugin is required (docker compose ...)"
docker info >/dev/null 2>&1 || die "cannot talk to the Docker daemon (is it running, and may this user use it?)"
[[ "$DATA" = /* ]] || die "--data must be an absolute path"
for r in "${REPOS[@]:-}"; do [[ -z "$r" || -d "$r" ]] || die "repository path $r does not exist"; done

rand() { head -c "$1" /dev/urandom | base64 | tr '+/' '-_' | tr -d '\n='; }

if [[ -f .env ]]; then
  say "Keeping existing .env"
else
  say "Writing .env"
  sed -e "s|^POSTGRES_PASSWORD=.*|POSTGRES_PASSWORD=$(rand 24)|" \
      -e "s|^RESTOREPROOF_HOST_DATA=.*|RESTOREPROOF_HOST_DATA=${DATA}|" \
      -e "s|^RESTOREPROOF_PORT=.*|RESTOREPROOF_PORT=${PORT}|" \
      -e "s|^RESTOREPROOF_BASE_URL=.*|RESTOREPROOF_BASE_URL=http://localhost:${PORT}|" .env.example > .env
  chmod 600 .env
fi

mkdir -p secrets
if [[ -f secrets/restoreproof.key ]]; then
  say "Keeping existing credential key"
else
  say "Generating the credential-encryption key (secrets/restoreproof.key)"
  (umask 077; head -c 32 /dev/urandom | base64 | tr '+/' '-_' > secrets/restoreproof.key)
  echo "    Back this file up somewhere safe. Without it, stored repository passwords cannot be decrypted."
fi
# The unprivileged web/scheduler containers (uid 10001) must be able to read the key.
# Otherwise run those containers as the key's owner, so the key can stay mode 0600.
if [[ "$(stat -c %u secrets/restoreproof.key)" != "10001" ]] && \
   ! { [[ -n "$SUDO" || $EUID -eq 0 ]] && ${SUDO:-env} -n chown 10001 secrets/restoreproof.key 2>/dev/null; }; then
  if ! grep -q '^RESTOREPROOF_UID=' .env; then
    echo "RESTOREPROOF_UID=$(stat -c %u secrets/restoreproof.key)" >> .env
  fi
  echo "    web and scheduler will run as uid $(stat -c %u secrets/restoreproof.key) (owner of the key file)"
fi

say "Preparing ${DATA}"
mkdir -p "$DATA" 2>/dev/null || $SUDO mkdir -p "$DATA" || die "cannot create $DATA (try --data with a writable path)"

if [[ ${#REPOS[@]} -gt 0 && -n "${REPOS[0]}" ]]; then
  say "Mounting ${#REPOS[@]} repository path(s) read-only into the worker (compose.override.yaml)"
  {
    echo "# Generated by install.sh. Repositories are mounted read-only; use /repos/<n> as the repository path."
    echo "services:"
    echo "  worker:"
    echo "    volumes:"
    i=1
    for r in "${REPOS[@]}"; do echo "      - ${r}:/repos/${i}:ro"; i=$((i + 1)); done
  } > compose.override.yaml
  i=1; for r in "${REPOS[@]}"; do echo "    ${r}  →  /repos/${i}"; i=$((i + 1)); done
fi

say "Building and starting RestoreProof"
docker compose up -d --build

say "Waiting for the dashboard"
for _ in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:${PORT}/api/v1/health" >/dev/null 2>&1; then break; fi
  sleep 2
done
curl -fsS "http://127.0.0.1:${PORT}/api/v1/health" >/dev/null 2>&1 || die "the web service did not come up; see: docker compose logs web"

say "Checking the installation"
docker compose exec -T worker restoreproof doctor || true

cat <<EOF

  RestoreProof is running:  http://127.0.0.1:${PORT}

  1. Open it and create the administrator account.
  2. The guided setup connects your backup and runs the first recovery test.
  3. For access from other machines, put a TLS reverse proxy in front (docs/installation.md).

  Update:  git pull && docker compose up -d --build
  Logs:    docker compose logs -f worker
EOF
